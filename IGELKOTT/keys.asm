.equ DEBOUNCE_DELAY = 255

.dseg
	KEYS_PRESSED:	.byte	1
	DEBOUNCE_FLAG:	.byte	1
	KEYS_STATE:		.byte	1

.cseg

INITIALIZE_KEYS:
	sts KEYS_PRESSED, r2
	sts DEBOUNCE_FLAG, r2
	sts KEYS_STATE, r2
	ret

CHECK_KEYS:
	push r16
	lds r16, KEYS_PRESSED
	tst r16
	breq NOT_PRESSED
	brne PRESSED_KEY

NOT_PRESSED:
	sbis PIND, 7
	rjmp UPDATE_DEBOUNCE_TIMER
	rjmp CLEAR_DEBOUNCE_TIMER
	
PRESSED_KEY:
	sbic PIND, 7
	rjmp UPDATE_DEBOUNCE_TIMER
	rjmp CLEAR_DEBOUNCE_TIMER

UPDATE_DEBOUNCE_TIMER:
	lds r16, KEYS_STATE
	inc r16
	sts KEYS_STATE, r16

	cpi r16, DEBOUNCE_DELAY
	brne CHECK_KEYS_EXIT

CHANGE_KEY_PRESSED:
	lds r16, KEYS_PRESSED
	com r16
	sts KEYS_PRESSED, r16
	rcall ADD_NOTE_MAYBE

CLEAR_DEBOUNCE_TIMER:
	clr r16
	sts KEYS_STATE, r16
	rjmp CHECK_KEYS_EXIT
	
CHECK_KEYS_EXIT:
	sts DEBOUNCE_DELAY, r2
	pop r16
	ret

ADD_NOTE_MAYBE:
	lds r16, KEYS_PRESSED
	tst r16
	brne CONTINUE
	ret

CONTINUE:
	note 440
	ret